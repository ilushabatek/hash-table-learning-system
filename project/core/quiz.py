def generate_test(num_questions=5):
    """Случайно выбирает вопросы и перемешивает варианты ответов."""
    selected = random.sample(QUESTIONS_BANK, num_questions)
    
    # Перемешиваем варианты ответов, чтобы правильный не был всегда первым
    test_data = []
    for q in selected:
        options = list(q["options"])
        correct_text = options[q["correct"]]
        
        random.shuffle(options)
        new_correct_index = options.index(correct_text)
        
        test_data.append({
            "question": q["question"],
            "options": options,
            "correct": new_correct_index
        })
    return test_data